CHAMBER_FLOOR = tile(48, 12, "<rect width='48' height='12' fill='#f3f0e8'/><path d='M0 .5h48M.5 0v12M24.5 0v12' stroke='#ddd6c8' stroke-width='1'/>")
NIGHT_STARS = tile(200, 100, "".join(f"<circle cx='{x}' cy='{y}' r='{r}' fill='white' opacity='{o}'/>" for x, y, r, o in
    [(12,14,.8,.9),(40,40,.6,.6),(71,9,.9,.8),(96,30,.5,.5),(130,18,.8,.9),(160,44,.6,.6),(184,12,.7,.8),(28,62,.5,.4),(110,58,.6,.5),(150,70,.5,.4),(190,52,.6,.6)]))

w_far, w_near = mesas('#b28fa6', '#a8603d', '#c97b4f')
n_far, n_near = mesas('#3a3560', '#2d2440', '#46385e')

themes = {
 'wasteland': dict(sky='linear-gradient(#5d8fd3,#f2c891 85%)', sun='#fff1c9', sunop='.7', clouds=CLOUDS, far=w_far, farop='.55', near=w_near,
                   ground='linear-gradient(#c98d58,#9a6440)', stripe='#b07548'),
 'namek':     dict(sky='linear-gradient(#7fcf9a,#dff3c6 85%)', sun='#fbffd8', sunop='.8', clouds=CLOUDS, far=NAMEK_FAR, farop='1', near=NAMEK_NEAR,
                   ground='linear-gradient(#5fb3a0,#3c8a80)', stripe='#4c9f8f'),
 'kamehouse': dict(sky='linear-gradient(#5aaee8,#d4f0ff 85%)', sun='#fffbe0', sunop='.9', clouds=CLOUDS, far=None, farop='1', near=KAME,
                   ground='linear-gradient(#f3dca2,#dcb874)', stripe='#e6c98b'),
 'chamber':   dict(sky='linear-gradient(#e6e2d9,#fbfaf6 60%)', sun='transparent', sunop='0', clouds=None, far=None, farop='1', near=CHAMBER_HOUSE,
                   ground='#f3f0e8 ' + CHAMBER_FLOOR + ' 0 0/48px 12px', stripe='#e0d9cb'),
 'night':     dict(sky='linear-gradient(#0e1433,#3b3f73 90%)', sun='#f2f0dc', sunop='.85', clouds=NIGHT_STARS, far=n_far, farop='.9', near=n_near,
                   ground='linear-gradient(#4a3a52,#2a2034)', stripe='#3b2e45'),
}
out = ["/* Generated by tools/scenes.py - arena backgrounds. Layers repeat in x so wide panels work. */",
 ".scene{position:absolute;inset:0;z-index:-2;overflow:hidden}",
 ".scene i{position:absolute;left:0;right:0;display:block}",
 ".scene .sky{inset:0}",
 ".scene .sun{left:auto;right:12%;bottom:30%;width:min(16%,60px);aspect-ratio:1;border-radius:50%}",
 ".scene .clouds{top:5%;height:60px;background-repeat:repeat-x;background-size:400px 60px;animation:cloudDrift 160s linear infinite}",
 "@keyframes cloudDrift{to{background-position-x:-400px}}",
 "@keyframes waveDrift{to{background-position-x:64px}}",
 ".scene .far{bottom:21%;height:22%;background-repeat:repeat-x;background-size:auto 100%;background-position:0 100%}",
 ".scene .sea{bottom:21%;height:20%;display:none}",
 ".scene .near{bottom:20%;height:26%;background-repeat:repeat-x;background-size:auto 100%;background-position:40px 100%}",
 ".scene .ground{bottom:0;height:21%}",
 ".scene .ground::after{content:'';position:absolute;left:0;right:0;top:35%;height:1px;opacity:.5;background:var(--stripe)}",
 "body[data-scene='kamehouse'] .scene .sea{display:block;background:" + SEA + " 0 0/100% 100%}",
 "body[data-scene='kamehouse'] .scene .sea::after{content:'';position:absolute;inset:20% 0 0;background:" + WAVES + " repeat-x 0 0/64px 16px;animation:waveDrift 7s linear infinite}",
 "body[data-scene='kamehouse'] .scene .near{background-repeat:no-repeat;background-position:right 6% bottom;height:34%;bottom:16%}",
 "body[data-scene='night'] .scene .clouds{top:0;height:60%;background-size:auto 100%;animation:none}",
 "body[data-scene='chamber'] .scene .near{background-repeat:no-repeat;background-position:left 8% bottom;height:30%;bottom:20%}",
]
for name, t in themes.items():
    sel = f"body[data-scene='{name}'] .scene" if name != 'wasteland' else ".scene"
    out.append(f"{sel} .sky{{background:{t['sky']}}}")
    out.append(f"{sel} .sun{{background:{t['sun']};opacity:{t['sunop']}}}")
    out.append(f"{sel} .clouds{{background-image:{t['clouds'] or 'none'}}}")
    out.append(f"{sel} .far{{background-image:{t['far'] or 'none'};opacity:{t['farop']}}}")
    out.append(f"{sel} .near{{background-image:{t['near']}}}")
    out.append(f"{sel} .ground{{background:{t['ground']};--stripe:{t['stripe']}}}")
open(__import__('sys').argv[1], 'w').write("\n".join(out) + "\n")
