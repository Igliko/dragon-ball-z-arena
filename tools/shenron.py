def segments(pts):
    out = []
    for i in range(len(pts) - 1):
        p0 = pts[i-1] if i > 0 else pts[i]; p1 = pts[i]; p2 = pts[i+1]
        p3 = pts[i+2] if i + 2 < len(pts) else pts[i+1]
        c1 = (p1[0] + (p2[0]-p0[0]) / 6, p1[1] + (p2[1]-p0[1]) / 6)
        c2 = (p2[0] - (p3[0]-p1[0]) / 6, p2[1] - (p3[1]-p1[1]) / 6)
        out.append((p1, c1, c2, p2))
    return out

def point(s, t):
    p1, c1, c2, p2 = s; u = 1 - t
    x = u**3*p1[0] + 3*u*u*t*c1[0] + 3*u*t*t*c2[0] + t**3*p2[0]
    y = u**3*p1[1] + 3*u*u*t*c1[1] + 3*u*t*t*c2[1] + t**3*p2[1]
    dx = 3*u*u*(c1[0]-p1[0]) + 6*u*t*(c2[0]-c1[0]) + 3*t*t*(p2[0]-c2[0])
    dy = 3*u*u*(c1[1]-p1[1]) + 6*u*t*(c2[1]-c1[1]) + 3*t*t*(p2[1]-c2[1])
    return x, y, dx, dy

def spikes(segs, start=30, every=11, size=5):
    out, acc, prev, dist = [], 0, None, 0
    for s in segs:
        for k in range(200):
            x, y, dx, dy = point(s, k / 200)
            if prev: step = math.hypot(x-prev[0], y-prev[1]); acc += step; dist += step
            prev = (x, y)
            if acc < every: continue
            acc = 0
            if dist < start: continue
            n = math.hypot(dx, dy) or 1; tx, ty = dx/n, dy/n; nx, ny = ty, -tx  # back side
            bx, by = x + nx*(WIDTH/2-1), y + ny*(WIDTH/2-1)
            a = (bx-tx*3, by-ty*3); b = (bx+tx*3, by+ty*3); c = (bx+nx*size+tx*2.5, by+ny*size+ty*2.5)
            out.append(f"M{a[0]:.1f} {a[1]:.1f}L{c[0]:.1f} {c[1]:.1f}L{b[0]:.1f} {b[1]:.1f}Z")
    return "".join(out)

segs = segments(SPINE)
d = f"M{SPINE[0][0]} {SPINE[0][1]}" + "".join(f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} {p2[0]} {p2[1]}" for _, c1, c2, p2 in segs)
arms = "".join(f'<g class="sr-arm" transform="translate({x} {y}) rotate({a})"><path d="M0 0C3 9 9 15 19 16"/>'
               f'<path class="sr-claw" d="M19 16l5-4M19 16l6 1M19 16l4 5"/></g>' for x, y, a in ARMS)
